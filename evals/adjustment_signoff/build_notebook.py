def build(path: Path) -> None:
    """Render the cells to a marimo notebook file."""
    codes = [code.strip("\n") for _, code in CELLS]
    cells = tuple(
        FileCell(name=name, code=code) for (name, _), code in zip(CELLS, codes, strict=True)
    )
    document = NotebookDocument(
        prefix=PREFIX,
        cells=cells,
        separators=("\n\n",) * (len(cells) - 1),
        suffix=SUFFIX,
    )
    analyses = analyse_cells(codes)
    unparsed = [
        name for (name, _), analysis in zip(CELLS, analyses, strict=True) if not analysis.parsed
    ]
    if unparsed:
        msg = f"these cell bodies do not parse: {', '.join(unparsed)}"
        raise SystemExit(msg)

    source = render_notebook(document, analyses, toplevel=frozenset())
    path.write_text(source, encoding="utf-8")
    print(f"wrote {path.name}: {len(cells)} cells, {len(source.splitlines())} lines")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent / NOTEBOOK_NAME,
        help="where to write the notebook",
    )
    build(parser.parse_args().out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
